import unittest
from backend.services.ioc_validator import validate_indicator
from backend.services.risk_engine import calculate_threat_risk, classify_risk
from backend.app import app, init_db
class IOCtests(unittest.TestCase):
 def test_valid_ipv4(self): self.assertEqual(validate_indicator('198.51.100.2')['indicator_type'],'IP')
 def test_invalid_ipv4(self): self.assertFalse(validate_indicator('999.1.1.1')['valid'])
 def test_ipv6(self): self.assertTrue(validate_indicator('2001:db8::1')['valid'])
 def test_domain(self): self.assertEqual(validate_indicator('EXAMPLE.COM')['normalized_value'],'example.com')
 def test_bad_domain(self): self.assertFalse(validate_indicator('bad domain')['valid'])
 def test_url(self): self.assertEqual(validate_indicator('https://example.com/x')['indicator_type'],'URL')
 def test_malformed_url(self): self.assertFalse(validate_indicator('https://')['valid'])
 def test_md5(self): self.assertEqual(validate_indicator('a'*32)['indicator_type'],'FILE_HASH')
 def test_sha1(self): self.assertEqual(validate_indicator('a'*40)['indicator_type'],'FILE_HASH')
 def test_sha256(self): self.assertEqual(validate_indicator('a'*64)['indicator_type'],'FILE_HASH')
 def test_cve(self): self.assertTrue(validate_indicator('CVE-2024-12345')['valid'])
 def test_bad_cve(self): self.assertFalse(validate_indicator('CVE-24-12')['valid'])
 def test_empty(self): self.assertFalse(validate_indicator('')['valid'])
class RiskTests(unittest.TestCase):
 def test_risk_bounded(self): self.assertTrue(0<=calculate_threat_risk('HIGH',80)<=100)
 def test_severity_affects_score(self): self.assertGreater(calculate_threat_risk('CRITICAL',80),calculate_threat_risk('LOW',80))
 def test_confidence_affects_score(self): self.assertGreater(calculate_threat_risk('HIGH',90),calculate_threat_risk('HIGH',20))
 def test_classify_high(self): self.assertEqual(classify_risk(75),'HIGH')
 def test_classify_critical(self): self.assertEqual(classify_risk(95),'CRITICAL')
class APITests(unittest.TestCase):
 @classmethod
 def setUpClass(cls): init_db()
 def setUp(self): self.client=app.test_client()
 def test_health(self): self.assertTrue(self.client.get('/api/health').json['ok'])
 def test_dataset_count(self): self.assertGreaterEqual(self.client.get('/api/stats').json['total'],2000)
 def test_search_valid(self): self.assertEqual(self.client.get('/api/search?indicator=198.51.100.2').status_code,200)
 def test_search_invalid(self): self.assertEqual(self.client.get('/api/search?indicator=bad%20value').status_code,400)
 def test_search_never_network(self): self.assertIn('No network',self.client.get('/api/search?indicator=198.51.100.2').json['notice'])
 def test_threats(self): self.assertGreater(len(self.client.get('/api/threats').json['items']),0)
 def test_filter_severity(self): self.assertTrue(all(x['severity']=='HIGH' for x in self.client.get('/api/threats?severity=HIGH').json['items']))
 def test_filter_category(self): self.assertTrue(all(x['threat_category']=='PHISHING' for x in self.client.get('/api/threats?category=PHISHING').json['items']))
 def test_invalid_sort(self): self.assertEqual(self.client.get('/api/threats?sort=bad').status_code,400)
 def test_detail_found(self): self.assertEqual(self.client.get('/api/threats/THR-2026-0001').status_code,200)
 def test_detail_missing(self): self.assertEqual(self.client.get('/api/threats/nope').status_code,404)
 def test_enrichment(self): self.assertIn('known',self.client.get('/api/enrich?indicator=198.51.100.2').json)
 def test_modules(self): self.assertGreaterEqual(len(self.client.get('/api/awareness/modules').json['items']),15)
 def test_quiz_size(self): self.assertGreaterEqual(len(self.client.get('/api/quiz').json['questions']),30)
 def test_quiz_scoring(self): self.assertEqual(self.client.post('/api/quiz/submit',json={'answers':[1]*32}).status_code,200)
 def test_bad_quiz(self): self.assertEqual(self.client.post('/api/quiz/submit',json={'answers':'bad'}).status_code,400)
 def test_vulnerability_awareness(self): self.assertIn('note',self.client.get('/api/vulnerabilities').json)
 def test_alerts(self): self.assertIn('items',self.client.get('/api/alerts').json)
 def test_alert_update_bad(self): self.assertEqual(self.client.patch('/api/alerts/1',json={'status':'BAD'}).status_code,400)
 def test_note_validation(self): self.assertEqual(self.client.post('/api/threats/THR-2026-0001/notes',json={'note':''}).status_code,400)
 def test_cve_records(self): self.assertGreater(len(self.client.get('/api/vulnerabilities').json['items']),0)
if __name__=='__main__': unittest.main()
